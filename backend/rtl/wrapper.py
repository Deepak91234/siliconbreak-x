"""Trusted generators: Basys 3 board wrapper (basys3_top), XDC, and the cl_core interface.

Nothing in this module consumes LLM output except the validated DesignSpec, whose
names are restricted identifiers. Package pins and IO standards come only from
boards/<id>/board.json, which tests/test_board.py cross-checks against the
official Digilent master XDC.

Hierarchy produced for every design:

    basys3_top  (generated here; fixed board port list; timing parameters)
      |- cl_input_cond  per bound input   (preverified library: sync + debounce)
      |- cl_core        (behaviour; written by the RTL generator / LLM)
      |- cl_sevenseg    when the spec has a display output (preverified library:
      |                 digit multiplexing + hex glyph decode onto seg/an)
      |- unused LEDs driven low; the display blanked when not used
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from backend.specifications.board import REPO_ROOT, Board, load_board
from backend.specifications.ir import DIGIT_BITS, DISPLAY_DIGITS, DesignSpec
from backend.specifications.timing import timing_params

LIBRARY_DIR = REPO_ROOT / "rtl" / "library"
LIBRARY_FILES = ("cl_sync2.v", "cl_debounce.v", "cl_input_cond.v", "cl_tick_div.v", "cl_edge_rise.v", "cl_sevenseg.v")
TOP_MODULE = "basys3_top"
CORE_MODULE = "cl_core"

GENERATED_BANNER = "GENERATED BY SILICONBREAK X (trusted generator) -- do not edit by hand"
LED_OFF = "1'b0"


@dataclass(frozen=True)
class CorePort:
    direction: str  # "input" | "output"
    name: str
    width: int
    comment: str

    def decl(self) -> str:
        rng = f"[{self.width - 1}:0] " if self.width > 1 else ""
        return f"{self.direction:<6} wire {rng}{self.name}"


def library_paths() -> list[Path]:
    return [LIBRARY_DIR / f for f in LIBRARY_FILES]


def core_ports(spec: DesignSpec) -> list[CorePort]:
    ports = [CorePort("input", "clk", 1, "100 MHz board clock (CLK_HZ in simulation)")]
    for i in spec.inputs:
        deb = f"debounced {i.debounce_ms:g} ms" if i.debounce_ms > 0 else "not debounced"
        ports.append(CorePort("input", i.name, 1, f"{i.board_signal}: synchronized, {deb}, active-high"))
    for o in spec.outputs:
        if o.port == "display":
            where = ", ".join(f"[{DIGIT_BITS * k + DIGIT_BITS - 1}:{DIGIT_BITS * k}]->digit AN{idx}"
                              for k, idx in enumerate(o.indices))
            ports.append(CorePort("output", o.name, o.width, f"seven-segment {{lit, hex[3:0]}} per digit: {where}"))
        else:
            leds = ", ".join(f"bit{k}->led[{idx}]" for k, idx in enumerate(o.indices))
            ports.append(CorePort("output", o.name, o.width, leds))
    return ports


def core_parameters(spec: DesignSpec, clk_hz: int | None = None) -> list[tuple[str, int, str]]:
    clk = clk_hz or spec.clock_hz
    return [(p.name, p.value, p.meaning) for p in timing_params(spec, clk) if p.core]


def core_interface(spec: DesignSpec) -> str:
    """The exact cl_core module header the RTL generator must implement."""
    params = core_parameters(spec)
    ports = core_ports(spec)
    lines = ["module cl_core #("]
    for n, (name, value, meaning) in enumerate(params):
        sep = "," if n < len(params) - 1 else ""
        lines.append(f"    parameter integer {name} = {value}{sep}  // {meaning}")
    lines.append(") (")
    for n, p in enumerate(ports):
        sep = "," if n < len(ports) - 1 else ""
        lines.append(f"    {p.decl()}{sep}  // {p.comment}")
    lines.append(");")
    return "\n".join(lines)


def generate_wrapper(spec: DesignSpec, board: Board | None = None) -> str:
    board = board or load_board(spec.board)
    params = timing_params(spec, spec.clock_hz)
    out: list[str] = [
        f"// {GENERATED_BANNER}",
        f"// Board: {board.name} ({board.part})",
        f"// Design: {spec.title}",
        "`default_nettype none",
        f"module {TOP_MODULE} #(",
    ]
    for n, p in enumerate(params):
        sep = "," if n < len(params) - 1 else ""
        out.append(f"    parameter integer {p.name} = {p.value}{sep}  // {p.meaning}")
    out += [
        ") (",
        "    input  wire        clk,",
        "    input  wire [15:0] sw,",
        "    input  wire        btnC,",
        "    input  wire        btnU,",
        "    input  wire        btnL,",
        "    input  wire        btnR,",
        "    input  wire        btnD,",
        "    output wire [15:0] led,",
        "    output wire [6:0]  seg,",
        "    output wire        dp,",
        "    output wire [3:0]  an",
        ");",
        "",
        "    // ---- input conditioning: 2-FF synchronizer + debounce (preverified library)",
    ]
    for i in spec.inputs:
        out.append(f"    wire {i.name};")
        out.append(
            f"    cl_input_cond #(.STABLE_CYCLES(DEBOUNCE_{i.name.upper()})) u_in_{i.name} "
            f"(.clk(clk), .d({i.board_signal}), .q({i.name}));"
        )
    out += ["", "    // ---- behaviour core"]
    for o in spec.outputs:
        rng = f"[{o.width - 1}:0] " if o.width > 1 else ""
        out.append(f"    wire {rng}{o.name};")
    core_params = [p for p in params if p.core]
    plist = ", ".join(f".{p.name}({p.name})" for p in core_params)
    conns = [".clk(clk)"] + [f".{i.name}({i.name})" for i in spec.inputs] + [f".{o.name}({o.name})" for o in spec.outputs]
    out.append(f"    {CORE_MODULE} #({plist}) u_core (")
    out.append("        " + ",\n        ".join(conns))
    out.append("    );")

    out += ["", "    // ---- LED mapping (unused LEDs are driven off)"]
    driver: dict[int, str] = {}
    for o in spec.outputs:
        if o.port != "led":
            continue
        for k, idx in enumerate(o.indices):
            driver[idx] = f"{o.name}[{k}]" if o.width > 1 else o.name
    for idx in range(16):
        out.append(f"    assign led[{idx}] = {driver.get(idx, LED_OFF)};")

    disp = spec.display_output
    if disp is None:
        out += [
            "",
            "    // ---- seven-segment display blanked (active-low cathodes and anodes)",
            "    assign seg = 7'b1111111;",
            "    assign dp  = 1'b1;",
            "    assign an  = 4'b1111;",
        ]
    else:
        slices = []
        for pos in reversed(range(DISPLAY_DIGITS)):
            if pos in disp.indices:
                k = disp.indices.index(pos)
                slices.append(f"{disp.name}[{DIGIT_BITS * k + DIGIT_BITS - 1}:{DIGIT_BITS * k}]")
            else:
                slices.append(f"{DIGIT_BITS}'b00000")
        out += [
            "",
            "    // ---- seven-segment display: multiplexing + glyph decode (preverified library)",
            f"    wire [{DIGIT_BITS * DISPLAY_DIGITS - 1}:0] _display_digits = {{{', '.join(slices)}}};  // AN3 .. AN0",
            "    cl_sevenseg #(.DIGIT_CYCLES(SEG_DIGIT_CYCLES)) u_display (",
            "        .clk(clk), .digits(_display_digits), .seg(seg), .an(an)",
            "    );",
            "    assign dp = 1'b1;  // decimal points off",
        ]
    used = {i.board_signal for i in spec.inputs}
    unused = [f"sw[{n}]" for n in range(16) if f"sw[{n}]" not in used]
    unused += [b for b in ("btnC", "btnU", "btnL", "btnR", "btnD") if b not in used]
    if unused:
        out += [
            "",
            "    // ---- board inputs this design does not use",
            "    /* verilator lint_off UNUSEDSIGNAL */",
            "    wire _unused_inputs = &{1'b0, " + ", ".join(unused) + "};",
            "    /* verilator lint_on UNUSEDSIGNAL */",
        ]
    out += ["endmodule", "`default_nettype wire", ""]
    return "\n".join(out)


def generate_xdc(spec: DesignSpec, board: Board | None = None) -> str:
    return board_xdc(board or load_board(spec.board))


def board_xdc(board: Board) -> str:
    """Constraints for a top module with the standard wrapper port list (every board port)."""
    if not board.verify_source_xdc():
        raise RuntimeError("board master XDC checksum mismatch; refusing to generate constraints")
    lines = [
        f"## {GENERATED_BANNER}",
        f"## Board: {board.name} ({board.part})",
        f"## Pins from boards/{board.id}/board.json, verified against {board.source_xdc.name} (sha256 {board.source_xdc_sha256[:16]}...)",
        "",
    ]
    for name, port in board.ports.items():
        for n, pin in enumerate(port.pins):
            target = f"{{{name}[{n}]}}" if port.is_vector else name
            lines.append(f"set_property -dict {{ PACKAGE_PIN {pin} IOSTANDARD {board.iostandard} }} [get_ports {target}]")
        if name == board.clock_port:
            half = board.clock_period_ns / 2
            lines.append(
                f"create_clock -add -name sys_clk_pin -period {board.clock_period_ns:.2f} -waveform {{0 {half:g}}} [get_ports {name}]"
            )
    lines += [
        "",
        "## Human-interface IO: inputs are synchronized in fabric, outputs drive LEDs/display.",
        "set_false_path -from [get_ports {sw[*] btnC btnU btnL btnR btnD}]",
        "set_false_path -to [get_ports {led[*] seg[*] dp an[*]}]",
        "",
    ]
    for key, value in board.config.items():
        lines.append(f"set_property {key} {value} [current_design]")
    lines.append("")
    return "\n".join(lines)
